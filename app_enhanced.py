@app.post("/upload-pdf")
@rate_limit("10/minute")
@log_function_call("upload_pdf")
async def upload_pdf(background_tasks: BackgroundTasks, file: UploadFile = File(...)):
    """Upload and process a PDF file"""
    try:
        # Validate file
        sanitized_filename = validate_pdf_file(file)
        
        # Build secure upload path
        upload_path = os.path.join(security_settings.base_upload_dir, sanitized_filename)
        
        # Security check - ensure path is within allowed directory
        abs_upload_path = os.path.abspath(upload_path)
        abs_base_dir = os.path.abspath(security_settings.base_upload_dir)
        
        if not abs_upload_path.startswith(abs_base_dir):
            raise ValidationError("Invalid upload path")
        
        # Save uploaded file
        with open(upload_path, "wb") as buffer:
            shutil.copyfileobj(file.file, buffer)
        
        # Process the PDF
        success = await insert_pdf(upload_path)
        
        if success:
            # Invalidate cache
            cache_manager.clear_pattern("pdf_list:*")
            
            # Update metrics
            PDF_UPLOADS.labels(status="success").inc()
            
            # Clear cache for this PDF
            cache_manager.invalidate_pdf_cache(sanitized_filename)
            
            background_tasks.add_task(logger.info, "PDF uploaded successfully", filename=sanitized_filename)
            
            return {
                "success": True, 
                "message": f"Successfully uploaded and processed {sanitized_filename}",
                "data": {"filename": sanitized_filename}
            }
        else:
            PDF_UPLOADS.labels(status="failed").inc()
            raise RAGException("Failed to process PDF", error_code="PROCESSING_ERROR")
            
    except RAGException:
        PDF_UPLOADS.labels(status="failed").inc()
        raise
    except Exception as e:
        PDF_UPLOADS.labels(status="failed").inc()
        log_and_raise_error(ProcessingError, f"Error uploading PDF: {str(e)}", processing_step="upload")


