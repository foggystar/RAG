def save_answer_to_file(query: str, answer: str, used_pdfs: List[str]) -> str:
    """Save LLM answer to a file in ./uploads directory"""
    try:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_query = "".join(c for c in query[:50] if c.isalnum() or c in (' ', '-', '_')).rstrip()
        safe_query = safe_query.replace(' ', '_')
        
        filename = f"{timestamp}_{safe_query}.md"
        filepath = os.path.join("uploads", filename)
        
        content = f"""# Query Response - {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## Query
{query}

## Used PDFs
{', '.join(used_pdfs)}

## Answer
{answer}

---
*Generated by RAG System*
"""
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        
        logger.info("Answer saved to file", filepath=filepath)
        return filename
        
    except Exception as e:
        logger.error("Error saving answer to file", error=str(e))
        return ""


def validate_pdf_file(file: UploadFile) -> str:
    """Validate and sanitize PDF file"""
    from utils.middleware import SecurityMiddleware
    
    if not file.filename:
        raise ValidationError("No filename provided")
    
    # Check file size
    if hasattr(file, 'size') and file.size > security_settings.max_file_size:
        raise FileTooLargeError(security_settings.max_file_size, file.size)
    
    # Check file extension
    if not file.filename.lower().endswith('.pdf'):
        raise InvalidFileTypeError(['.pdf'], os.path.splitext(file.filename)[1])
    
    # Sanitize filename
    sanitized_filename = SecurityMiddleware.validate_filename(file.filename)
    
    # Ensure unique filename
    base_name, ext = os.path.splitext(sanitized_filename)
    counter = 1
    final_filename = sanitized_filename
    
    while os.path.exists(os.path.join(security_settings.base_upload_dir, final_filename)):
        final_filename = f"{base_name}_{counter}{ext}"
        counter += 1
    
    return final_filename


